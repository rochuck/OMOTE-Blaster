#!/usr/bin/env python3
"""Generate src/kodi_logo.h from assets/kodi.png.

Same pipeline as gen_apple_tv_logo.py: crop the white logo off its dark
background, scale it to the 32px OLED row preserving aspect, and pack it 1-bit
MSB-first for Adafruit_GFX drawBitmap().
"""
import sys

from PIL import Image

TARGET_H = 32          # OLED panel height
THRESHOLD = 128        # white-ink cutoff after grayscale

g = Image.open("assets/kodi.png").convert("L")

# Crop to the bright (ink) pixels so scaling isn't wasted on the dark margins.
mask = g.point(lambda v: 255 if v > THRESHOLD else 0)
g = g.crop(mask.getbbox())

# Scale to the panel height, preserving aspect; round width to whole pixels.
W = max(1, round(g.width * TARGET_H / g.height))
H = TARGET_H
g = g.resize((W, H), Image.LANCZOS)
px = g.load()

# Pack MSB-first, one row at a time, padding each row to a byte boundary.
row_bytes = (W + 7) // 8
out = bytearray()
for y in range(H):
    for b in range(row_bytes):
        byte = 0
        for bit in range(8):
            x = b * 8 + bit
            if x < W and px[x, y] > THRESHOLD:
                byte |= 1 << (7 - bit)
        out.append(byte)

# ASCII preview to stderr so the shape can be eyeballed when regenerating.
for y in range(H):
    print("".join("#" if px[x, y] > THRESHOLD else " " for x in range(W)), file=sys.stderr)

lines = []
lines.append("#pragma once\n")
lines.append("// Auto-generated by scripts/gen_kodi_logo.py from assets/kodi.png —")
lines.append("// 1-bit, MSB-first, for Adafruit_GFX drawBitmap(). Do not hand-edit;")
lines.append("// regenerate from the script.")
lines.append(f"static const int KODI_LOGO_WIDTH  = {W};")
lines.append(f"static const int KODI_LOGO_HEIGHT = {H};")
lines.append("static const unsigned char KODI_LOGO_BITS[] = {")
for i in range(0, len(out), 12):
    chunk = ", ".join(f"0x{b:02X}" for b in out[i:i + 12])
    lines.append(f"    {chunk},")
lines.append("};")

with open("src/kodi_logo.h", "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"wrote src/kodi_logo.h ({W}x{H}, {len(out)} bytes)", file=sys.stderr)
