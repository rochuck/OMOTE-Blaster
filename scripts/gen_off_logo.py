#!/usr/bin/env python3
"""Generate src/off_logo.h from assets/off.png.

Same pipeline as gen_lyrion_logo.py: crop to the bright ink, fit inside the
full 128x32 panel box preserving aspect (whichever axis binds), then pack it
1-bit MSB-first for Adafruit_GFX drawBitmap().
"""
import sys

from PIL import Image

MAX_W = 128            # OLED panel width
MAX_H = 32             # OLED panel height
THRESHOLD = 128        # light-ink cutoff after grayscale

g = Image.open("assets/off.png").convert("L")

# Crop to the bright (ink) pixels so scaling isn't wasted on the dark margins.
mask = g.point(lambda v: 255 if v > THRESHOLD else 0)
g = g.crop(mask.getbbox())

# Fit inside the panel box, preserving aspect; whichever axis binds wins.
scale = min(MAX_W / g.width, MAX_H / g.height)
W = max(1, round(g.width * scale))
H = max(1, round(g.height * scale))
g = g.resize((W, H), Image.LANCZOS)
px = g.load()

# Pack MSB-first, one row at a time, padding each row to a byte boundary.
row_bytes = (W + 7) // 8
out = bytearray()
for y in range(H):
    for b in range(row_bytes):
        byte = 0
        for bit in range(8):
            x = b * 8 + bit
            if x < W and px[x, y] > THRESHOLD:
                byte |= 1 << (7 - bit)
        out.append(byte)

# ASCII preview to stderr so the shape can be eyeballed when regenerating.
for y in range(H):
    print("".join("#" if px[x, y] > THRESHOLD else " " for x in range(W)), file=sys.stderr)

lines = []
lines.append("#pragma once\n")
lines.append("// Auto-generated by scripts/gen_off_logo.py from assets/off.png —")
lines.append("// 1-bit, MSB-first, for Adafruit_GFX drawBitmap(). Do not hand-edit;")
lines.append("// regenerate from the script.")
lines.append(f"static const int OFF_LOGO_WIDTH  = {W};")
lines.append(f"static const int OFF_LOGO_HEIGHT = {H};")
lines.append("static const unsigned char OFF_LOGO_BITS[] = {")
for i in range(0, len(out), 12):
    chunk = ", ".join(f"0x{b:02X}" for b in out[i:i + 12])
    lines.append(f"    {chunk},")
lines.append("};")

with open("src/off_logo.h", "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"wrote src/off_logo.h ({W}x{H}, {len(out)} bytes)", file=sys.stderr)
