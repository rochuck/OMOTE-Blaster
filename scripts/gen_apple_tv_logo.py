#!/usr/bin/env python3
"""Generate src/apple_tv_logo.h from assets/atv.png.

The source is the white "apple tv" wordmark on a dark background. We crop to the
ink, scale it to fit the 32px-tall OLED row while preserving aspect, and pack it
1-bit MSB-first to match the format Adafruit_GFX drawBitmap() and zethus_logo.h
expect. The wordmark already includes the "tv" text, so the display draws this
bitmap directly — no separately-printed label.
"""
import sys

from PIL import Image

TARGET_H = 32          # OLED panel height
THRESHOLD = 128        # white-ink cutoff after grayscale

g = Image.open("assets/atv.png").convert("L")

# Crop to the bright (ink) pixels so scaling isn't wasted on the dark margins.
mask = g.point(lambda v: 255 if v > THRESHOLD else 0)
bbox = mask.getbbox()
g = g.crop(bbox)

# Scale to the panel height, preserving aspect; round width to whole pixels.
W = max(1, round(g.width * TARGET_H / g.height))
H = TARGET_H
g = g.resize((W, H), Image.LANCZOS)
px = g.load()

# Pack MSB-first, one row at a time, padding each row to a byte boundary.
row_bytes = (W + 7) // 8
out = bytearray()
for y in range(H):
    for b in range(row_bytes):
        byte = 0
        for bit in range(8):
            x = b * 8 + bit
            if x < W and px[x, y] > THRESHOLD:
                byte |= 1 << (7 - bit)
        out.append(byte)

# ASCII preview to stderr so the shape can be eyeballed when regenerating.
for y in range(H):
    print("".join("#" if px[x, y] > THRESHOLD else " " for x in range(W)), file=sys.stderr)

lines = []
lines.append("#pragma once\n")
lines.append("// Auto-generated by scripts/gen_apple_tv_logo.py from assets/atv.png —")
lines.append("// 1-bit, MSB-first, for Adafruit_GFX drawBitmap(). Do not hand-edit;")
lines.append("// regenerate from the script.")
lines.append(f"static const int APPLE_TV_LOGO_WIDTH  = {W};")
lines.append(f"static const int APPLE_TV_LOGO_HEIGHT = {H};")
lines.append("static const unsigned char APPLE_TV_LOGO_BITS[] = {")
for i in range(0, len(out), 12):
    chunk = ", ".join(f"0x{b:02X}" for b in out[i:i + 12])
    lines.append(f"    {chunk},")
lines.append("};")

with open("src/apple_tv_logo.h", "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"wrote src/apple_tv_logo.h ({W}x{H}, {len(out)} bytes)", file=sys.stderr)
